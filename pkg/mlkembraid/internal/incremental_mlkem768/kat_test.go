package incremental_mlkem768

// KAT tests for GenerateKey, Encaps1, Encaps2, Decaps, ValidatePKBytes.
//
// Cross-validation strategy: use Go stdlib crypto/mlkem as the oracle.
// For a fixed 64-byte seed (d || z), the stdlib's NewDecapsulationKey768
// produces the same key material as our kemKeyGen. We verify:
//   1. Our GenerateKey (random seed) produces a key that round-trips through
//      Encaps1 + Encaps2 + Decaps and yields the same shared secret.
//   2. A stdlib-generated key pair, when fed into our Encaps1/Encaps2, produces
//      a ciphertext that the stdlib's Decapsulate accepts and matches.
//   3. Our Decaps inverts a ciphertext produced by the stdlib encapsulate.
//   4. ValidatePKBytes accepts well-formed keys and rejects malformed ones.
//
// Rust oracle: sparsepostquantumratchet::incremental_mlkem768::test::incremental_mlkem768_round_trip

import (
	"bytes"
	"crypto/mlkem"
	"crypto/rand"
	"crypto/sha3"
	"testing"
)

// TestGenerateKeyRoundTrip verifies that GenerateKey + Encaps1 + Encaps2 + Decaps
// produces matching shared secrets.
func TestGenerateKeyRoundTrip(t *testing.T) {
	pk1, pk2, dk, err := GenerateKey()
	if err != nil {
		t.Fatalf("GenerateKey error: %v", err)
	}

	// Sizes must be correct.
	if len(pk1) != PublicKey1Size {
		t.Fatalf("pk1 size %d, want %d", len(pk1), PublicKey1Size)
	}
	if len(pk2) != PublicKey2Size {
		t.Fatalf("pk2 size %d, want %d", len(pk2), PublicKey2Size)
	}
	if len(dk) != DecapsKeySize {
		t.Fatalf("dk size %d, want %d", len(dk), DecapsKeySize)
	}

	// Encaps1 using pk1.
	var randomness [SharedSecretSize]byte
	if _, err = rand.Read(randomness[:]); err != nil {
		t.Fatalf("rand.Read: %v", err)
	}
	ct1, es, ss1, err := Encaps1(pk1[:], randomness)
	if err != nil {
		t.Fatalf("Encaps1 error: %v", err)
	}

	// Encaps2 using encaps state and pk2.
	ct2, err := Encaps2(es[:], pk2[:])
	if err != nil {
		t.Fatalf("Encaps2 error: %v", err)
	}

	// Decaps must produce the same shared secret as Encaps1.
	ss2, err := Decaps(dk[:], ct1[:], ct2[:])
	if err != nil {
		t.Fatalf("Decaps error: %v", err)
	}

	if ss1 != ss2 {
		t.Errorf("Decaps shared secret mismatch\nEncaps1 ss: %x\nDecaps  ss: %x", ss1, ss2)
	}
}

// TestGenerateKeyVsStdlib verifies that our key generation is compatible with the
// Go stdlib's crypto/mlkem. Given a known 64-byte seed (d || z), the stdlib's
// NewDecapsulationKey768 produces an encapsulation key ek = ByteEncode12(t) || rho.
// Our kemKeyGen must produce the same pk1, pk2, and dk from the same seed.
func TestGenerateKeyVsStdlib(t *testing.T) {
	// Fixed 64-byte seed: d (first 32) || z (last 32).
	var seed [64]byte
	for i := range seed[:32] {
		seed[i] = byte(i + 1)
	}
	for i := range seed[32:] {
		seed[32+i] = byte(i + 0x80)
	}

	// Stdlib key generation from d || z.
	stdlibDK, err := mlkem.NewDecapsulationKey768(seed[:])
	if err != nil {
		t.Fatalf("NewDecapsulationKey768: %v", err)
	}
	stdlibEK := stdlibDK.EncapsulationKey()
	ekBytes := stdlibEK.Bytes() // 1184 bytes = ByteEncode12(t) || rho

	// Our key generation from the same d || z.
	pk1, pk2, dk, err := kemKeyGen(seed[:32], seed[32:])
	if err != nil {
		t.Fatalf("kemKeyGen error: %v", err)
	}

	// pk2 must match the first 1152 bytes of the stdlib ek.
	if !bytes.Equal(pk2[:], ekBytes[:PublicKey2Size]) {
		t.Error("pk2 mismatch with stdlib ek t_ntt portion")
	}

	// pk1[:32] (rho) must match ek[1152:1184] from stdlib.
	if !bytes.Equal(pk1[:32], ekBytes[PublicKey2Size:]) {
		t.Errorf("pk1 rho mismatch\ngot:  %x\nwant: %x", pk1[:32], ekBytes[PublicKey2Size:])
	}

	// pk1[32:64] (H(ek)) must match SHA3-256(ek).
	h := sha3.New256()
	if _, err := h.Write(ekBytes); err != nil {
		t.Fatalf("h.Write: %v", err)
	}
	var expectedHEK [32]byte
	h.Sum(expectedHEK[:0])
	if !bytes.Equal(pk1[32:], expectedHEK[:]) {
		t.Errorf("pk1 H(ek) mismatch\ngot:  %x\nwant: %x", pk1[32:], expectedHEK)
	}

	// The dk rho field must match the stdlib ek rho.
	dkRho := dk[2*PublicKey2Size : 2*PublicKey2Size+32]
	if !bytes.Equal(dkRho, ekBytes[PublicKey2Size:]) {
		t.Errorf("dk rho mismatch\ngot:  %x\nwant: %x", dkRho, ekBytes[PublicKey2Size:])
	}

	// The dk H(ek) field must match our computed H(ek).
	dkHEK := dk[2*PublicKey2Size+32 : 2*PublicKey2Size+64]
	if !bytes.Equal(dkHEK, expectedHEK[:]) {
		t.Errorf("dk H(ek) field mismatch\ngot:  %x\nwant: %x", dkHEK, expectedHEK)
	}

	// The dk z field must match the seed z.
	dkZ := dk[2*PublicKey2Size+64:]
	if !bytes.Equal(dkZ, seed[32:]) {
		t.Errorf("dk z mismatch\ngot:  %x\nwant: %x", dkZ, seed[32:])
	}
}

// TestDecapsVsStdlib verifies that our Decaps produces the same shared secret
// as the stdlib for a ciphertext generated by the stdlib encapsulate.
//
// Flow: stdlib KeyGen → stdlib EncapsulationKey.Encapsulate → our Decaps.
func TestDecapsVsStdlib(t *testing.T) {
	// Use a fixed seed for reproducibility.
	var seed [64]byte
	for i := range seed[:32] {
		seed[i] = byte(i + 3)
	}
	for i := range seed[32:] {
		seed[32+i] = byte(i + 0xC0)
	}

	stdlibDK, err := mlkem.NewDecapsulationKey768(seed[:])
	if err != nil {
		t.Fatalf("NewDecapsulationKey768: %v", err)
	}

	// Generate our dk from same seed.
	_, _, dk, err := kemKeyGen(seed[:32], seed[32:])
	if err != nil {
		t.Fatalf("kemKeyGen: %v", err)
	}

	// Encapsulate using the stdlib.
	stdlibEK := stdlibDK.EncapsulationKey()
	stdlibSS, stdlibCT := stdlibEK.Encapsulate()

	// ct = ct1 (960) || ct2 (128).
	ct1 := stdlibCT[:Ciphertext1Size]
	ct2 := stdlibCT[Ciphertext1Size:]

	// Our Decaps must match the stdlib shared secret.
	ourSS, err := Decaps(dk[:], ct1, ct2)
	if err != nil {
		t.Fatalf("Decaps error: %v", err)
	}

	if !bytes.Equal(ourSS[:], stdlibSS) {
		t.Errorf("Decaps/stdlib shared secret mismatch\nour: %x\nstd: %x", ourSS, stdlibSS)
	}
}

// TestEncaps1Encaps2VsStdlib verifies that our Encaps1+Encaps2 output is
// accepted by the stdlib Decapsulate.
//
// Flow: stdlib KeyGen → extract pk1/pk2 → our Encaps1 → our Encaps2 → stdlib Decapsulate.
func TestEncaps1Encaps2VsStdlib(t *testing.T) {
	var seed [64]byte
	for i := range seed[:32] {
		seed[i] = byte(i + 7)
	}
	for i := range seed[32:] {
		seed[32+i] = byte(i + 0xD0)
	}

	stdlibDK, err := mlkem.NewDecapsulationKey768(seed[:])
	if err != nil {
		t.Fatalf("NewDecapsulationKey768: %v", err)
	}

	// Extract pk1, pk2 from our key generation (same seed).
	pk1, pk2, _, err := kemKeyGen(seed[:32], seed[32:])
	if err != nil {
		t.Fatalf("kemKeyGen: %v", err)
	}

	// Encaps1 + Encaps2 using our implementation.
	var randomness [SharedSecretSize]byte
	if _, err = rand.Read(randomness[:]); err != nil {
		t.Fatalf("rand.Read: %v", err)
	}
	ct1, es, ourSS, err := Encaps1(pk1[:], randomness)
	if err != nil {
		t.Fatalf("Encaps1: %v", err)
	}
	ct2, err := Encaps2(es[:], pk2[:])
	if err != nil {
		t.Fatalf("Encaps2: %v", err)
	}

	// Combine ciphertexts and decapsulate with stdlib.
	fullCT := append(ct1[:], ct2[:]...)
	stdlibSS, err := stdlibDK.Decapsulate(fullCT)
	if err != nil {
		t.Fatalf("stdlib Decapsulate: %v", err)
	}

	if !bytes.Equal(ourSS[:], stdlibSS) {
		t.Errorf("encaps1+2 shared secret vs stdlib Decapsulate mismatch\nour: %x\nstd: %x", ourSS, stdlibSS)
	}
}

// TestDecapsImplicitRejection verifies that Decaps returns the implicit-rejection
// value (not the real shared secret) when the ciphertext is modified.
func TestDecapsImplicitRejection(t *testing.T) {
	pk1, pk2, dk, err := GenerateKey()
	if err != nil {
		t.Fatalf("GenerateKey: %v", err)
	}

	var randomness [SharedSecretSize]byte
	if _, err = rand.Read(randomness[:]); err != nil {
		t.Fatalf("rand.Read: %v", err)
	}
	ct1, es, ss1, err := Encaps1(pk1[:], randomness)
	if err != nil {
		t.Fatalf("Encaps1: %v", err)
	}
	ct2, err := Encaps2(es[:], pk2[:])
	if err != nil {
		t.Fatalf("Encaps2: %v", err)
	}

	// Flip a bit in ct1 to create an invalid ciphertext.
	ct1Bad := ct1
	ct1Bad[0] ^= 0x01

	ssImplicit, err := Decaps(dk[:], ct1Bad[:], ct2[:])
	if err != nil {
		t.Fatalf("Decaps with bad ct1 error: %v", err)
	}

	// The implicit-rejection result must differ from the real shared secret.
	if ssImplicit == ss1 {
		t.Error("Decaps returned real SS for invalid ciphertext (no implicit rejection)")
	}

	// For the same invalid ciphertext, Decaps must be deterministic.
	ssImplicit2, err := Decaps(dk[:], ct1Bad[:], ct2[:])
	if err != nil {
		t.Fatalf("Decaps second call error: %v", err)
	}
	if ssImplicit != ssImplicit2 {
		t.Error("Decaps is not deterministic for invalid ciphertext")
	}
}

// TestValidatePKBytesAccepts verifies that ValidatePKBytes accepts a well-formed key pair.
func TestValidatePKBytesAccepts(t *testing.T) {
	pk1, pk2, _, err := GenerateKey()
	if err != nil {
		t.Fatalf("GenerateKey: %v", err)
	}
	if err = ValidatePKBytes(pk1[:], pk2[:]); err != nil {
		t.Errorf("ValidatePKBytes rejected valid key pair: %v", err)
	}
}

// TestValidatePKBytesRejectsHashMismatch verifies that ValidatePKBytes rejects
// a key pair where H(ek) in pk1 has been tampered with.
func TestValidatePKBytesRejectsHashMismatch(t *testing.T) {
	pk1, pk2, _, err := GenerateKey()
	if err != nil {
		t.Fatalf("GenerateKey: %v", err)
	}

	// Flip a bit in the H(ek) portion of pk1.
	pk1Bad := pk1
	pk1Bad[32] ^= 0xFF

	if err = ValidatePKBytes(pk1Bad[:], pk2[:]); err == nil {
		t.Error("ValidatePKBytes should reject pk1 with tampered H(ek)")
	}
}

// TestValidatePKBytesRejectsUnreducedCoeff verifies that ValidatePKBytes rejects
// a pk2 containing a coefficient >= q.
func TestValidatePKBytesRejectsUnreducedCoeff(t *testing.T) {
	pk1, pk2, _, err := GenerateKey()
	if err != nil {
		t.Fatalf("GenerateKey: %v", err)
	}

	// Overwrite the first three bytes of pk2 to encode coefficient value 4095 (>= q=3329).
	// ByteEncode12 packs two 12-bit values per 3 bytes: d1 = b[0]|(b[1]<<8)&0xFFF, d2 = (b[1]>>4)|(b[2]<<4).
	// Setting b[0]=0xFF, b[1]=0xFF gives d1=0xFFF=4095 >= q.
	pk2Bad := pk2
	pk2Bad[0] = 0xFF
	pk2Bad[1] = 0xFF
	pk2Bad[2] = 0xFF

	if err = ValidatePKBytes(pk1[:], pk2Bad[:]); err == nil {
		t.Error("ValidatePKBytes should reject pk2 with unreduced coefficient")
	}
}

// TestDecapsInvalidInputs verifies error handling for bad-length inputs to Decaps.
func TestDecapsInvalidInputs(t *testing.T) {
	tests := []struct {
		name string
		dk   []byte
		ct1  []byte
		ct2  []byte
	}{
		{"nil dk", nil, make([]byte, Ciphertext1Size), make([]byte, Ciphertext2Size)},
		{"short dk", make([]byte, 10), make([]byte, Ciphertext1Size), make([]byte, Ciphertext2Size)},
		{"short ct1", make([]byte, DecapsKeySize), make([]byte, 10), make([]byte, Ciphertext2Size)},
		{"short ct2", make([]byte, DecapsKeySize), make([]byte, Ciphertext1Size), make([]byte, 10)},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if _, decErr := Decaps(tt.dk, tt.ct1, tt.ct2); decErr == nil {
				t.Errorf("Decaps should reject invalid input: %s", tt.name)
			}
		})
	}
}

// TestValidatePKBytesInvalidLengths verifies error handling for bad-length inputs.
func TestValidatePKBytesInvalidLengths(t *testing.T) {
	if e := ValidatePKBytes(make([]byte, 32), make([]byte, PublicKey2Size)); e == nil {
		t.Error("ValidatePKBytes should reject pk1 of wrong length")
	}
	if e := ValidatePKBytes(make([]byte, PublicKey1Size), make([]byte, 100)); e == nil {
		t.Error("ValidatePKBytes should reject pk2 of wrong length")
	}
}
